#!/usr/bin/env bash
# Upgrade test on docker: a distro set up by RomBooter 1.2.0 (whose start script rejects --dpi) is
# booted the way the current app does it (rb-launch.sh with the bundled setup and --dpi). The
# launcher must update start script + guest rb-session without reinstalling anything, and the
# desktop must come up with the app's password and DPI.
#   tests/e2e-upgrade.sh [distro]       default: ubuntu (needs docker + java, package mirrors)
set -uo pipefail
source "$(dirname "$0")/lib.sh"
d=${1:-ubuntu}
OLD="$ROOT/tests/fixtures/old/rombooter-setup-1.2.0.sh"
WORK=$(mktemp -d); export PATH="$ROOT/tests/e2e:$PATH" RB_VNC_PORT=25901 HOME_D="$WORK/home"
[[ -f /root/.ccr/ca-bundle.crt && -z ${RB_E2E_CA:-} ]] && export RB_E2E_CA=/root/.ccr/ca-bundle.crt
PASSWORD=Ab3dEf7h
mkdir -p "$HOME_D"
alias=$d; [[ $d == arch ]] && alias=archlinux

echo "1. set up $d with RomBooter 1.2.0"
if ( source "$OLD"; DISTRO=$d; DE=xfce; USER_NAME=rom; RES=1280x608; PREFIX=/usr HOME=$HOME_D TMPDIR=$WORK
     resolve_distro; install_distro && provision && write_start_script ) >"$WORK/old-setup.log" 2>&1; then
  pass "1.2.0 setup ($(grep -m1 -o 'generated by rombooter-setup [0-9.]*' "$HOME_D/start_$d.sh"))"
else
  fail "1.2.0 setup"; tail -n 10 "$WORK/old-setup.log"; finish; exit
fi
out=$(HOME=$HOME_D bash "$HOME_D/start_$d.sh" --res 1024x576 --pass "$PASSWORD" --de xfce --dpi 144 2>&1)
check "the old start script rejects --dpi (the reported bug)" grep -q "unknown argument '--dpi'" <<<"$out"

echo "2. boot with the current app's launcher"
launch() { HOME=$HOME_D timeout 300 bash -c "$(cat "$ROOT/app/src/main/assets/rb-launch.sh")" rb-launch "$d" "$(cat "$SETUP")" "$@"; }
if launch --res 1024x576 --pass "$PASSWORD" --de xfce --dpi 144 >"$WORK/launch.log" 2>&1; then
  pass "app-style boot with --dpi succeeds: $(grep -o 'READY [0-9]*' "$WORK/launch.log")"
else
  fail "boot after update"; tail -n 15 "$WORK/launch.log"; cat "$HOME_D/.rombooter/refresh-$d.log" 2>/dev/null | tail -n 10
fi
check "scripts were updated, not reinstalled" grep -q "updating the $d scripts 1.2.0 ->" "$WORK/launch.log"
check "no packages installed during the update" bash -c '! grep -qi -e "apt-get" -e "Provisioning" "$1"' _ "$HOME_D/.rombooter/refresh-$d.log"
check "guest rb-session is the new one" docker exec "rb-e2e-$alias" grep -q -- '--dpi)' /usr/local/bin/rb-session
docker exec "rb-e2e-$alias" sh -c 'pgrep -a Xvnc' | grep -q -- '-dpi 144' && pass "desktop runs with the app's DPI (Xvnc -dpi 144)" \
  || fail "Xvnc without -dpi 144"
java "$ROOT/tests/e2e/RfbProbe.java" "$RB_VNC_PORT" "$PASSWORD" 1024x576 >"$WORK/probe.log" 2>&1 \
  && pass "VNC login with the app's password + first frame" || { fail "VNC probe"; tail -n 5 "$WORK/probe.log"; }
launch --stop >/dev/null 2>&1 && pass "stop" || fail "stop"

[[ -n ${KEEP:-} ]] || docker rm -f "rb-e2e-$alias" >/dev/null 2>&1
finish
