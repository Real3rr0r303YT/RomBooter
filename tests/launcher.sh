#!/usr/bin/env bash
# Tests for the app's Termux entry points (app/src/main/assets), invoked exactly like the app does:
#   bash -c "<rb-launch.sh>" rb-launch DISTRO SETUP ARGS... (every Boot/Stop)
#   bash -c "<rb-setup.sh>" rb-setup SETUP DISTRO SESSIONS  ("Set up <distro>" button)
set -uo pipefail
source "$(dirname "$0")/lib.sh"
ASSETS="$ROOT/app/src/main/assets"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
export HOME="$tmp/home"; mkdir -p "$HOME"
# The app passes the setup script bundled in the APK as the second argument
BUNDLED=$(cat "$SETUP")
launch() { local d=$1; shift; OUT=$(bash -c "$(cat "$ASSETS/rb-launch.sh")" rb-launch "$d" "$BUNDLED" "$@" 2>"$tmp/err"); RC=$?; ERR=$(cat "$tmp/err"); }

echo "rb-launch.sh"
check "shellcheck" shellcheck -s bash "$ASSETS/rb-launch.sh" "$ASSETS/rb-setup.sh" "$ASSETS/rb-phantom.sh"
for d in arch gentoo ubuntu alpine kali fedora debian; do
  launch "$d" --res 1280x576 --pass Abc12345 --de xfce
  check "$d without start script -> exit 4 (was Termux error 150)" test "$RC" = 4
done
check "message names the missing script" grep -q "start_debian.sh not found" <<<"$ERR"
launch "../etc" --stop
check "unknown/unsafe distro key rejected (exit 2)" test "$RC" = 2

# A start script written by 1.0.1 (no version marker)
printf '#!/bin/bash\nALIAS=debian\necho "legacy $*"\n' >"$HOME/start_debian.sh"
launch debian --res 1280x576 --pass Abc12345 --de xfce
check "1.0.x start script -> exit 6 (outdated, broken VNC password)" test "$RC" = 6
launch debian --stop
check "--stop still runs a 1.0.x start script" grep -q "legacy --stop" <<<"$OUT"

# A start script generated by the current setup is executed with all arguments
gen debian xfce "$HOME" >/dev/null
launch debian --res 12
check "current start script is executed (its own exit 2 for a bad value)" test "$RC" = 2
check "arguments reach the start script" grep -q "res must be WxH" <<<"$ERR"
check "start script carries the version marker" grep -Eq '^# start_debian\.sh - generated by rombooter-setup (1\.([1-9]|[1-9][0-9]+)|[2-9][0-9]*)\.' "$HOME/start_debian.sh"

echo "existing installs: update instead of 'unknown argument --dpi'"
OLD="$ROOT/tests/fixtures/old/rombooter-setup-1.2.0.sh"
export FAKE_ROOT="$tmp/containers"
mkdir -p "$FAKE_ROOT/archlinux-alarm/usr/local/bin"
old_install() { # distro alias user res: start script + guest rb-session as the 1.2.0 setup wrote them
  rm -f "$HOME/start_$1.sh"
  ( source "$OLD"; DISTRO=$1; DE=xfce; USER_NAME=$3; RES=$4; PREFIX=/usr; resolve_distro; ALIAS=$2
    write_start_script >/dev/null; write_session >"$FAKE_ROOT/$2/usr/local/bin/rb-session" )
  chmod 755 "$FAKE_ROOT/$2/usr/local/bin/rb-session"
}
old_install arch archlinux-alarm phone 1600x720
check "fixture: the 1.2.0 start script rejects --dpi (the reported bug)" \
  bash -c '[[ $(bash "$1" --dpi 134 --status 2>&1) == *"unknown argument '"'"'--dpi'"'"'"* ]]' _ "$HOME/start_arch.sh"
PATH="$ROOT/tests/fixtures/guest:$PATH" launch arch --res 1600x720 --pass Abc12345 --de xfce --dpi 134 --status
check "app-style start with --dpi on a 1.2.0 install succeeds" test "$RC" = 0
check "...because the scripts were updated first" grep -q "updating the arch scripts 1.2.0 ->" <<<"$ERR"
check "start script now carries the current version" grep -q "generated by rombooter-setup $(sed -n 's/^readonly VERSION="\(.*\)"$/\1/p' "$SETUP")$" "$HOME/start_arch.sh"
check "container alias, user and resolution kept" grep -q "^ALIAS=archlinux-alarm; KEY=arch; DE=xfce; RES=1600x720; GUEST_USER=phone$" "$HOME/start_arch.sh"
check "guest rb-session updated inside the container (knows --dpi)" grep -q -- "--dpi)" "$FAKE_ROOT/archlinux-alarm/usr/local/bin/rb-session"
check "no package or rootfs work during the update" bash -c '! grep -q -e rb-provision -e install "$1"' _ "$FAKE_ROOT/calls"
launch arch --res 1600x720 --pass Abc12345 --dpi 134 --status
check "second start: no update needed" bash -c '[[ $1 == 0 && $2 != *updating* ]]' _ "$RC" "$ERR"

old_install arch archlinux-alarm phone 1600x720
PATH="$ROOT/tests/fixtures/broken:$PATH" launch arch --res 1600x720 --pass Abc12345 --dpi 134 --status
check "update impossible -> still starts: --dpi is dropped for the old script" test "$RC" = 0
check "...and the failed update is reported" grep -q "updating failed" <<<"$ERR"

launch debian --status --some-future-option 42 --another-flag
check "current start script ignores unknown options (exit 0)" test "$RC" = 0
check "...with a warning" grep -q "ignoring unknown argument '--some-future-option'" <<<"$ERR"

echo "rb-setup.sh"
rm -f "$HOME/rombooter-setup.sh"
printf 'echo "setup $*"\n' >"$tmp/fake-setup"
OUT=$(bash -c "$(cat "$ASSETS/rb-setup.sh")" rb-setup "$(cat "$tmp/fake-setup")" arch xfce 2>&1); RC=$?
check "runs the bundled setup with --distro/--de/--yes" grep -q "setup --distro arch --de xfce --yes" <<<"$OUT"
check "writes ~/rombooter-setup.sh with mode 700" test "$(stat -c %a "$HOME/rombooter-setup.sh")" = 700
OUT=$(bash -c "$(cat "$ASSETS/rb-setup.sh")" rb-setup 'if then fi (' arch xfce 2>&1); RC=$?
check "a damaged setup script is refused" test "$RC" != 0
check "...and does not replace the previous copy" grep -q 'echo "setup' "$HOME/rombooter-setup.sh"
# The real setup script survives the trip through argv byte for byte
bash -c "$(cat "$ASSETS/rb-setup.sh")" rb-setup "$(cat "$SETUP")" arch xfce >/dev/null 2>&1
check "real rombooter-setup.sh arrives unchanged in ~" cmp -s "$SETUP" "$HOME/rombooter-setup.sh"

echo "rb-phantom.sh (phantom process killer, no PC)"
export FAKE_ADB_STATE="$tmp/adb"
phantom() { OUT=$(PATH="$ROOT/tests/fixtures/android:$PATH" bash -c "$(cat "$ASSETS/rb-phantom.sh")" rb-phantom "$@" 2>&1); RC=$?; }
phantom <<<$'37000\n123456\n41000'
check "pairs and connects over Wireless debugging" grep -q "pair 127.0.0.1:37000 123456" "$tmp/adb/calls"
check "sets max_phantom_processes and the monitor flag" test "$(cat "$tmp/adb/max")-$(cat "$tmp/adb/flag")" = "2147483647-false"
check "verifies and reports success" grep -q "phantom process killer is off" <<<"$OUT"
phantom <<<$'37000\n999999\n41000'
check "a wrong pairing code stops with a clear message" bash -c '[[ $1 != 0 ]] && grep -q "Pairing failed" <<<"$2"' _ "$RC" "$OUT"
phantom --undo <<<$'37000\n123456\n41000'
check "--undo restores Android's defaults" test "$(cat "$tmp/adb/flag")" = true
FAKE_SDK=30 phantom </dev/null
check "Android 11 and older: nothing to do" grep -q "no phantom process killer" <<<"$OUT"
FAKE_SDK=34 phantom <<<"n"
check "Android 14+: points to the developer option first" grep -q "Disable child process restrictions" <<<"$OUT"

finish
