# rb-launch.sh - run by the RomBooter app inside Termux as
#   bash -c "<this file>" rb-launch DISTRO BUNDLED_SETUP [start script arguments...]
# Android does not let the app write into Termux's home, so instead of calling ~/start_DISTRO.sh
# directly (Termux error 150 "file not found" when it is missing), Termux runs this check first.
# BUNDLED_SETUP is the rombooter-setup.sh shipped in the app. A start script from an older setup is
# updated from it before it runs (rombooter-setup.sh --refresh: start script + guest rb-session,
# no packages, no new rootfs), so new app options such as --dpi never break existing installs.
# Exit codes: 4 = not set up, 6 = set up by RomBooter 1.0.x (needs a full setup), else the start script's.
k=${1:-}
setup=${2:-}
shift 2 2>/dev/null || shift $#
case $k in
  arch|gentoo|debian|ubuntu|alpine|kali|fedora) ;;
  *) echo "ERROR: unknown distro '$k'" >&2; exit 2 ;;
esac
s="$HOME/start_$k.sh"
if [ ! -f "$s" ]; then
  echo "ERROR: $s not found - $k is not set up yet" >&2
  exit 4
fi

ver=$(sed -n 's/^# start_[a-z]*\.sh - generated by rombooter-setup \([0-9][0-9.]*\)$/\1/p' "$s" | head -n 1)
older() { # older A B: version A < version B
  [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | head -n 1)" = "$1" ]
}
# --stop must work for whatever started the session
[ "${1:-}" = --stop ] && exec bash "$s" "$@"

if [ -z "$ver" ] || older "$ver" 1.1; then
  echo "ERROR: $s comes from an older RomBooter setup (1.0.x) whose VNC password handling is broken" >&2
  exit 6
fi

bundled=$(printf '%s\n' "$setup" | sed -n 's/^readonly VERSION="\([0-9][0-9.]*\)"$/\1/p' | head -n 1)
if [ -n "$bundled" ] && older "$ver" "$bundled"; then
  echo "RomBooter: updating the $k scripts $ver -> $bundled (rootfs and packages stay as they are)" >&2
  mkdir -p "$HOME/.rombooter"
  f="$HOME/rombooter-setup.sh"
  if printf '%s\n' "$setup" >"$f.new" && bash -n "$f.new" && mv -f "$f.new" "$f" && chmod 700 "$f" &&
     bash "$f" --refresh --distro "$k" >"$HOME/.rombooter/refresh-$k.log" 2>&1; then
    ver=$bundled
  else
    echo "WARN: updating failed (see ~/.rombooter/refresh-$k.log); starting with the old scripts" >&2
  fi
fi

# Never pass a start script options it does not know (only needed if the update above failed)
if older "$ver" 1.3; then
  n=$#
  while [ "$n" -gt 0 ]; do
    a=$1; shift; n=$((n - 1))
    if [ "$a" = --dpi ] && [ "$n" -gt 0 ]; then shift; n=$((n - 1)); continue; fi
    case $a in --dpi=*) continue ;; esac
    set -- "$@" "$a"
  done
fi
exec bash "$s" "$@"
